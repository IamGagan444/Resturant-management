export const LANGS = [
  { code: "en", label: "English" },
  { code: "hi", label: "हिन्दी" },
  { code: "or", label: "ଓଡ଼ିଆ" },
  { code: "te", label: "తెలుగు" },
] as const;
export type Lang = (typeof LANGS)[number]["code"];

const catalogues: Record<Lang, Catalogue> = { en, hi, or, te };
const isLang = (v: unknown): v is Lang => LANGS.some((l) => l.code === v);

export function translate(lang: Lang, key: MsgKey, vars?: Record<string, string | number>): string {
  const s = catalogues[lang][key];
  return vars ? s.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m)) : s;
}

export type T = (key: MsgKey, vars?: Record<string, string | number>) => string;

const Ctx = createContext<{ lang: Lang; setLang: (l: Lang) => void; t: T }>({
  lang: "en",
  setLang: () => {},
  t: (k, v) => translate("en", k, v),
});

/** Language = guest's last choice on this phone, else the restaurant's default. */
export function LangProvider({ fallback, children }: { fallback: string; children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(isLang(fallback) ? fallback : "en");
  useEffect(() => {
    try {
      const saved = localStorage.getItem("rms.lang");
      if (isLang(saved)) setLangState(saved);
    } catch {
      // private mode: keep the default
    }
  }, []);
  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);
  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    try {
      localStorage.setItem("rms.lang", l);
    } catch {
      // ignore
    }
  }, []);
  const value = useMemo(() => ({ lang, setLang, t: ((k, v) => translate(lang, k, v)) as T }), [lang, setLang]);
  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

export const useI18n = () => useContext(Ctx);
